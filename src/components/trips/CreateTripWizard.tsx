import React, { useState, useMemo } from 'react';
import {
  X, Plane, Calendar, DollarSign, MapPin, Sparkles, Search, ArrowRight, ArrowLeft, Check, CheckCircle2
} from 'lucide-react';
import { Trip, GLOBAL_DESTINATIONS } from '../../types/trip';
import { getCurrencyFlag, getCurrencySymbol } from '../../utils/helpers';
import { fetchLiveExchangeRate } from '../../services/fxRatesService';

interface CreateTripWizardProps {
  isOpen: boolean;
  onClose: () => void;
  onCreateTrip: (trip: Trip) => void;
  currentUserId?: string | null;
}

export default function CreateTripWizard({
  isOpen,
  onClose,
  onCreateTrip,
  currentUserId
}: CreateTripWizardProps) {
  const [currentStep, setCurrentStep] = useState<1 | 2 | 3>(1);

  // Step 1: Destination
  const [countrySearch, setCountrySearch] = useState('');
  const [selectedCountryCode, setSelectedCountryCode] = useState('JP');
  const [city, setCity] = useState('Tokio');
  const [title, setTitle] = useState('Aventura en Tokio');

  // Step 2: Dates
  const [startDate, setStartDate] = useState('2026-11-15');
  const [endDate, setEndDate] = useState('2026-11-28');
  const [autoGenerateDays, setAutoGenerateDays] = useState(true);

  // Step 3: Finance
  const baseCurrency = 'USD';
  const [localCurrency, setLocalCurrency] = useState('JPY');
  const [approxRate, setApproxRate] = useState('155');
  const [budgetBase, setBudgetBase] = useState('1500');
  const [isFetchingRate, setIsFetchingRate] = useState(false);

  const selectedCountry = useMemo(() => {
    return GLOBAL_DESTINATIONS.find(c => c.code === selectedCountryCode) || GLOBAL_DESTINATIONS[0];
  }, [selectedCountryCode]);

  const filteredCountries = useMemo(() => {
    if (!countrySearch.trim()) return GLOBAL_DESTINATIONS;
    const q = countrySearch.toLowerCase().trim();
    return GLOBAL_DESTINATIONS.filter(c =>
      c.name.toLowerCase().includes(q) ||
      c.code.toLowerCase().includes(q) ||
      c.suggestedCities.some(city => city.toLowerCase().includes(q))
    );
  }, [countrySearch]);

  const tripDurationDays = useMemo(() => {
    try {
      const s = new Date(startDate);
      const e = new Date(endDate);
      const diff = Math.ceil((e.getTime() - s.getTime()) / (1000 * 60 * 60 * 24)) + 1;
      return Math.max(1, diff || 1);
    } catch {
      return 14;
    }
  }, [startDate, endDate]);

  const dailyBudget = useMemo(() => {
    const total = Number(budgetBase) || 0;
    return tripDurationDays > 0 ? Math.round(total / tripDurationDays) : 0;
  }, [budgetBase, tripDurationDays]);

  if (!isOpen) return null;

  const handleCountrySelect = (code: string) => {
    setSelectedCountryCode(code);
    const c = GLOBAL_DESTINATIONS.find(item => item.code === code);
    if (c) {
      const defaultCity = c.suggestedCities[0] || c.name;
      setCity(defaultCity);
      setTitle(`Viaje a ${defaultCity}`);
      setLocalCurrency(c.defaultCurrency);
      setApproxRate(c.approxRateUSD.toString());

      // Try fetching live exchange rate for this country
      fetchLiveExchangeRate(baseCurrency, c.defaultCurrency, code).then(res => {
        if (res.rate && res.rate > 0) {
          setApproxRate(res.rate.toString());
        }
      });
    }
  };

  const handleCitySelect = (cityName: string) => {
    setCity(cityName);
    setTitle(`Aventura en ${cityName}`);
  };

  const handleFetchCurrentLiveRate = async () => {
    setIsFetchingRate(true);
    try {
      const res = await fetchLiveExchangeRate(baseCurrency, localCurrency, selectedCountryCode);
      if (res.rate && res.rate > 0) {
        setApproxRate(res.rate.toString());
      }
    } finally {
      setIsFetchingRate(false);
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    const newTrip: Trip = {
      id: 'trip-' + Date.now(),
      userId: currentUserId || 'user-admin-jools',
      title: title.trim() || `Viaje a ${city}`,
      destinationCity: city.trim() || 'Destino',
      countryCode: selectedCountryCode,
      flagEmoji: selectedCountry?.flag || '✈️',
      startDate,
      endDate,
      baseCurrency,
      localCurrency,
      exchangeRate: Number(approxRate) || 1,
      budgetTotalBase: Number(budgetBase) || 1000,
      isActive: true,
      notes: autoGenerateDays ? 'Días calculados automáticamente.' : undefined
    };

    onCreateTrip(newTrip);
    onClose();
  };

  return (
    <div className="modal-backdrop-overlay animate-fade-in" onClick={onClose}>
      <div className="create-trip-wizard-card animate-scale-up" onClick={(e) => e.stopPropagation()}>
        
        {/* Wizard Header */}
        <div className="wizard-modal-header">
          <div className="wizard-header-title-box">
            <div className="wizard-icon-badge">
              <Plane size={24} className="text-sky" />
            </div>
            <div>
              <h3>Asistente de Nuevo Viaje</h3>
              <p>Paso {currentStep} de 3 • Planifica tu próxima aventura</p>
            </div>
          </div>

          <button
            type="button"
            className="btn-modal-close"
            onClick={onClose}
            aria-label="Cerrar asistente"
          >
            <X size={20} />
          </button>
        </div>

        {/* Stepper Indicator */}
        <div className="wizard-stepper-track">
          <div className={`step-dot-item ${currentStep >= 1 ? 'completed' : ''} ${currentStep === 1 ? 'active' : ''}`}>
            <span className="dot-num">{currentStep > 1 ? <Check size={12} /> : '1'}</span>
            <span className="dot-label">Destino</span>
          </div>
          <div className={`step-connector ${currentStep >= 2 ? 'active' : ''}`}></div>

          <div className={`step-dot-item ${currentStep >= 2 ? 'completed' : ''} ${currentStep === 2 ? 'active' : ''}`}>
            <span className="dot-num">{currentStep > 2 ? <Check size={12} /> : '2'}</span>
            <span className="dot-label">Fechas</span>
          </div>
          <div className={`step-connector ${currentStep >= 3 ? 'active' : ''}`}></div>

          <div className={`step-dot-item ${currentStep === 3 ? 'active' : ''}`}>
            <span className="dot-num">3</span>
            <span className="dot-label">Presupuesto</span>
          </div>
        </div>

        {/* Wizard Body Form */}
        <form onSubmit={handleSubmit} className="wizard-body-form">
          
          {/* STEP 1: DESTINATION */}
          {currentStep === 1 && (
            <div className="wizard-step-content animate-fade-in">
              <div className="form-group">
                <div className="country-search-header-row">
                  <label className="form-label mb-0">
                    <span>1. Elige tu País de Destino ({filteredCountries.length}):</span>
                  </label>
                  <div className="country-search-input-wrapper">
                    <Search size={14} className="country-search-icon" />
                    <input
                      type="text"
                      placeholder="Buscar país o ciudad..."
                      value={countrySearch}
                      onChange={(e) => setCountrySearch(e.target.value)}
                      className="country-search-input"
                    />
                  </div>
                </div>

                <div className="country-chips-grid">
                  {filteredCountries.map(c => (
                    <button
                      key={c.code}
                      type="button"
                      className={`country-chip-btn ${selectedCountryCode === c.code ? 'active' : ''}`}
                      onClick={() => handleCountrySelect(c.code)}
                    >
                      <span className="chip-flag">{c.flag}</span>
                      <span className="chip-name">{c.name}</span>
                    </button>
                  ))}
                </div>
              </div>

              {/* Suggested Cities */}
              {selectedCountry && selectedCountry.suggestedCities.length > 0 && (
                <div className="form-group">
                  <label className="form-label">
                    <span>Ciudades recomendadas en {selectedCountry.name}:</span>
                  </label>
                  <div className="city-chips-row">
                    {selectedCountry.suggestedCities.map(cName => (
                      <button
                        key={cName}
                        type="button"
                        className={`city-chip-btn ${city === cName ? 'active' : ''}`}
                        onClick={() => handleCitySelect(cName)}
                      >
                        📍 {cName}
                      </button>
                    ))}
                  </div>
                </div>
              )}

              {/* Title & City Inputs */}
              <div className="form-row-2">
                <div className="form-group">
                  <label className="form-label">
                    <MapPin size={14} />
                    <span>Ciudad Específica:</span>
                  </label>
                  <input
                    type="text"
                    value={city}
                    onChange={(e) => setCity(e.target.value)}
                    placeholder="Ej: Tokio, Kioto, Madrid"
                    className="form-input"
                    required
                  />
                </div>

                <div className="form-group">
                  <label className="form-label">
                    <span>Título del Viaje:</span>
                  </label>
                  <input
                    type="text"
                    value={title}
                    onChange={(e) => setTitle(e.target.value)}
                    placeholder="Ej: Aventura en Japón"
                    className="form-input"
                    required
                  />
                </div>
              </div>
            </div>
          )}

          {/* STEP 2: DATES */}
          {currentStep === 2 && (
            <div className="wizard-step-content animate-fade-in">
              <div className="form-row-2">
                <div className="form-group">
                  <label className="form-label">
                    <Calendar size={14} />
                    <span>Fecha de Llegada / Inicio:</span>
                  </label>
                  <input
                    type="date"
                    value={startDate}
                    onChange={(e) => setStartDate(e.target.value)}
                    className="form-input"
                    required
                  />
                </div>

                <div className="form-group">
                  <label className="form-label">
                    <Calendar size={14} />
                    <span>Fecha de Retorno / Fin:</span>
                  </label>
                  <input
                    type="date"
                    value={endDate}
                    onChange={(e) => setEndDate(e.target.value)}
                    className="form-input"
                    required
                  />
                </div>
              </div>

              {/* Duration Preview Card */}
              <div className="duration-preview-card">
                <div className="duration-pill">
                  <Sparkles size={16} className="text-sky" />
                  <span>Duración calculada: <strong>{tripDurationDays} días de viaje</strong></span>
                </div>
                <p>
                  Desde el <strong>{startDate}</strong> hasta el <strong>{endDate}</strong> en {selectedCountry.flag} {city}.
                </p>
              </div>

              {/* Auto Generate Days Checkbox */}
              <label className="checkbox-auto-days-label">
                <input
                  type="checkbox"
                  checked={autoGenerateDays}
                  onChange={(e) => setAutoGenerateDays(e.target.checked)}
                />
                <div>
                  <strong>Generar estructura de días en el tablero Kanban</strong>
                  <p>Crea automáticamente las columnas del Día 1 al Día {tripDurationDays} con sus fechas correspondientes.</p>
                </div>
              </label>
            </div>
          )}

          {/* STEP 3: BUDGET & CURRENCY */}
          {currentStep === 3 && (
            <div className="wizard-step-content animate-fade-in">
              <div className="form-row-3">
                <div className="form-group">
                  <label className="form-label">
                    <DollarSign size={14} />
                    <span>Presupuesto ({baseCurrency}):</span>
                  </label>
                  <input
                    type="number"
                    value={budgetBase}
                    onChange={(e) => setBudgetBase(e.target.value)}
                    placeholder="1500"
                    className="form-input"
                    required
                  />
                </div>

                <div className="form-group">
                  <label className="form-label">
                    <span>Moneda Local:</span>
                  </label>
                  <div className="currency-field-with-flag">
                    <span className="field-flag">{selectedCountry.flag}</span>
                    <input
                      type="text"
                      value={localCurrency}
                      onChange={(e) => setLocalCurrency(e.target.value.toUpperCase())}
                      className="form-input"
                      maxLength={4}
                      required
                    />
                  </div>
                </div>

                <div className="form-group">
                  <div className="label-with-refresh">
                    <label className="form-label mb-0">
                      <span>Cotización (x 1 {baseCurrency}):</span>
                    </label>
                    <button
                      type="button"
                      className="btn-text-fetch-rate"
                      onClick={handleFetchCurrentLiveRate}
                      disabled={isFetchingRate}
                    >
                      {isFetchingRate ? '...' : 'En vivo'}
                    </button>
                  </div>
                  <input
                    type="number"
                    step="any"
                    value={approxRate}
                    onChange={(e) => setApproxRate(e.target.value)}
                    className="form-input"
                    required
                  />
                </div>
              </div>

              {/* Financial KPI Summary */}
              <div className="wizard-kpis-summary">
                <div className="wizard-kpi-item">
                  <span className="kpi-title">Meta de Gasto Diario:</span>
                  <strong className="kpi-val">${dailyBudget} {baseCurrency} / día</strong>
                </div>
                <div className="wizard-kpi-item">
                  <span className="kpi-title">Equivalente en Moneda Local:</span>
                  <strong className="kpi-val">
                    {selectedCountry.flag} {getCurrencySymbol(localCurrency)} {Math.round((Number(budgetBase) || 0) * (Number(approxRate) || 1)).toLocaleString()} {localCurrency}
                  </strong>
                </div>
              </div>
            </div>
          )}

          {/* Wizard Footer Controls */}
          <div className="wizard-footer-controls">
            {currentStep > 1 ? (
              <button
                type="button"
                className="btn-secondary"
                onClick={() => setCurrentStep((prev) => (prev - 1) as any)}
              >
                <ArrowLeft size={16} />
                <span>Anterior</span>
              </button>
            ) : (
              <button
                type="button"
                className="btn-secondary"
                onClick={onClose}
              >
                Cancelar
              </button>
            )}

            {currentStep < 3 ? (
              <button
                type="button"
                className="btn-primary"
                onClick={() => setCurrentStep((prev) => (prev + 1) as any)}
              >
                <span>Continuar</span>
                <ArrowRight size={16} />
              </button>
            ) : (
              <button
                type="submit"
                className="btn-primary btn-submit-wizard"
              >
                <Sparkles size={16} />
                <span>🚀 Crear y Comenzar Mi Viaje</span>
              </button>
            )}
          </div>

        </form>

      </div>
    </div>
  );
}

